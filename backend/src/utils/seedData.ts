export async function seedDatabase() {
  try {
    await connectDB();

    console.log('🌱 Updating database seed data to match exact design categories, products, services, gallery & reviews...');

    // Upsert categories
    for (const cat of initialCategories) {
      await Category.findOneAndUpdate({ slug: cat.slug }, cat, { upsert: true, new: true });
    }
    console.log(`✅ Upserted ${initialCategories.length} categories.`);

    // Upsert products
    for (const prod of initialProducts) {
      await Product.findOneAndUpdate({ slug: prod.slug }, prod, { upsert: true, new: true });
    }
    console.log(`✅ Upserted ${initialProducts.length} products.`);

    // Upsert services
    for (const serv of initialServices) {
      await Service.findOneAndUpdate({ slug: serv.slug }, serv, { upsert: true, new: true });
    }
    console.log(`✅ Upserted ${initialServices.length} services.`);

    // Upsert gallery items
    for (const item of initialGalleryItems) {
      await GalleryItem.findOneAndUpdate(
        { $or: [{ slug: item.slug }, { title: item.title }] },
        item,
        { upsert: true, new: true }
      );
    }
    console.log(`✅ Upserted ${initialGalleryItems.length} gallery items.`);

    // Upsert reviews
    for (const rev of initialReviews) {
      await Review.findOneAndUpdate({ authorName: rev.authorName }, rev, { upsert: true, new: true });
    }
    console.log(`✅ Upserted ${initialReviews.length} reviews.`);

    console.log('🎉 Database updated successfully.');
  } catch (error) {
    console.error('❌ Seeding error:', error);
  }
}

if (require.main === module) {
  seedDatabase().then(() => {
    process.exit(0);
  });
}
